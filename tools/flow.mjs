// Dev-only: drive the whole app with D-pad keys, Enter (pinch) and Escape/history.back (Back).
import {chromium} from 'playwright';
const base = process.argv[2] ?? 'http://127.0.0.1:4174/';
const browser = await chromium.launch({headless: true, executablePath: '/opt/google/chrome/chrome'});
const page = await browser.newPage({viewport: {width: 600, height: 600}});
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => m.type() === 'error' && errors.push(m.text()));
let fails = 0;
const check = (n, ok, x = '') => (ok || fails++, console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${x ? ` — ${x}` : ''}`));
const focused = () => page.evaluate(() => document.activeElement?.getAttribute('aria-label') || document.activeElement?.textContent?.trim().slice(0, 24) || 'none');
const key = async (k, wait = 150) => (await page.keyboard.press(k), await page.waitForTimeout(wait));
const saveData = () => page.evaluate(() => JSON.parse(localStorage.getItem('cutup.save.v1') || '{}'));

await page.goto(base, {waitUntil: 'load'});
await page.evaluate(() => localStorage.clear());
await page.reload({waitUntil: 'load'});
await page.waitForTimeout(900);
check('Home focuses Drive', (await focused()).startsWith('Drive'), await focused());
await key('ArrowDown');
check('Down → Pursuit', (await focused()).startsWith('Pursuit'), await focused());
await key('ArrowDown');
check('Down → Garage', (await focused()).startsWith('Garage'), await focused());
await key('Enter', 700);
check('Garage opens on the car stage', (await focused()).startsWith('Pocket R'), await focused());
await key('ArrowRight', 400);
check('Right flips to the next car', (await focused()).startsWith('Ronin GT'), await focused());
await key('ArrowDown');
check('Down → paints', (await page.evaluate(() => document.activeElement?.classList.contains('swatch'))), await focused());
await key('ArrowDown');
check('Down → buy button', (await focused()).includes('Need') || (await focused()).includes('Unlocks'), await focused());
await key('Escape', 600);
check('Back returns home to Garage', (await focused()).startsWith('Garage'), await focused());
await key('ArrowDown');
await key('Enter', 700);
check('Career opens', !!(await page.$('.career')));
await key('Escape', 600);
await key('ArrowUp');
await key('ArrowUp');
await key('ArrowUp');
check('Back at Drive', (await focused()).startsWith('Drive'), await focused());
await key('Enter', 900);
check('First run shows the tutorial', !!(await page.$('.tutorial')));
await key('Escape', 700);
check('Back from tutorial goes home', !!(await page.$('.home')), await focused());
await key('Enter', 900);
await key('Enter', 600);
check('Run starts after "Let\'s go"', !(await page.$('.tutorial')) && !!(await page.$('.drive-surface')));
check('Focus holds on the driving surface', (await focused()).startsWith('Driving'), await focused());
await page.waitForTimeout(3500);
const x0 = await page.evaluate(() => document.querySelector('.drive') && 1);
await key('ArrowLeft', 400);
check('Swipe left during a run keeps focus', (await focused()).startsWith('Driving'), await focused());
await page.evaluate(() => history.back());
await page.waitForTimeout(500);
check('Glasses Back (history.back) pauses the run', !!(await page.$('.pause')), await focused());
check('Pause focuses Resume', (await focused()).includes('Resume'), await focused());
await key('Escape', 400);
check('Back again resumes', !(await page.$('.pause')) && !!(await page.$('.drive-surface')));
await key('Escape', 400);
await key('ArrowDown');
await key('ArrowDown');
await key('Enter', 900);
check('Quit to menu from pause', !!(await page.$('.home')), await focused());
// Full run until a crash, steering at random.
await page.focus('[data-nav="drive"]');
await key('Enter', 4500);
for (let i = 0; i < 160 && !(await page.$('.results')); i++) await key(i % 3 ? 'ArrowRight' : 'ArrowLeft', 220);
await page.waitForTimeout(1500);
check('Crash leads to results', !!(await page.$('.results')));
check('Results focus Drive again', (await focused()).includes('Drive again'), await focused());
const sv = await saveData();
check('Run was saved (runs, cash, XP)', sv.totals?.runs === 1 && sv.xp > 0, `runs ${sv.totals?.runs}, cash ${sv.cash}, xp ${sv.xp}`);
await key('Escape', 700);
check('Back from results goes home', !!(await page.$('.home')), await focused());
check('History stays within the 5-entry cap', (await page.evaluate(() => history.length)) <= 5, `length ${await page.evaluate(() => history.length)}`);
// ---- Pursuit ----
await page.focus('[data-nav="pursuit"]');
await key('Enter', 900);
check('Pursuit opens on heat 1', !!(await page.$('.pursuit')) && (await focused()).startsWith('Heat 1'), await focused());
await key('ArrowRight', 300);
check('Heat 2 is locked at first', (await focused()).includes('locked'), await focused());
check('Locked heat explains the unlock', ((await page.textContent('.heat-note')) ?? '').includes('unlocks when you escape heat 1'));
await key('ArrowLeft', 300);
await key('Enter', 1200);
check('First chase shows the pursuit tutorial', ((await page.textContent('.tutorial h2').catch(() => '')) ?? '').includes('Lose the cops'));
await key('Escape', 900);
check('Back from the pursuit tutorial goes home', !!(await page.$('.home')), await focused());
await page.focus('[data-nav="pursuit"]');
await key('Enter', 900);
await key('Enter', 1200);
await key('Enter', 600);
check('Chase starts', !(await page.$('.tutorial')) && !!(await page.$('.drive-surface')));
check('Focus holds on the driving surface (chase)', (await focused()).startsWith('Driving'), await focused());
await page.evaluate(() => history.back());
await page.waitForTimeout(600);
check('Back pauses the chase', !!(await page.$('.pause')), await focused());
await key('Escape', 600);
for (let i = 0; i < 260 && !(await page.$('.results')); i++) await key(i % 4 ? 'ArrowRight' : 'ArrowLeft', 200);
await page.waitForTimeout(1500);
const outcome = (await page.textContent('.res-outcome').catch(() => '')) ?? '';
check('Chase ends in results (busted or escaped)', /BUSTED|ESCAPED/.test(outcome), outcome);
check('Results focus Chase again', (await focused()).includes('Chase again'), await focused());
const sv2 = await saveData();
check('Chase was saved', sv2.pursuit && sv2.pursuit.busts + sv2.pursuit.escapes[0] >= 1, JSON.stringify(sv2.pursuit));
await page.focus('.res-actions .ghost-btn');
await key('Enter', 900);
check('Heat button returns to the heat picker', !!(await page.$('.pursuit')), await focused());
await key('Escape', 800);
check('Back from the heat picker goes home', !!(await page.$('.home')), await focused());
check('History stays within the 5-entry cap (after chase)', (await page.evaluate(() => history.length)) <= 5, `length ${await page.evaluate(() => history.length)}`);
check('No console errors', errors.length === 0, errors.join(' | '));
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
await browser.close();
